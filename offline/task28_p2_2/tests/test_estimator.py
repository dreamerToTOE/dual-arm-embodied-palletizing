"""Independent mathematical controls; all inputs here are synthetic."""
from dataclasses import replace

import numpy as np
import pytest
from scipy.linalg import lstsq
from scipy.spatial.transform import Rotation

from offline.task28_p2_2.estimator import Contract, Observation, estimate
from task28_validator.model import RobotModel

NAMES = tuple(f"left_fr3_joint{i}" for i in range(1, 8))
CONTRACT = Contract(NAMES, "world", "left_fr3_side_suction_tcp", .1, .01)


def sample(J=None, q=None, wrench=None):
    if J is None:
        J = np.c_[np.diag([1., 2., 3., 4., 5., 6.]), np.ones(6) * .1]
    if q is None:
        q = np.zeros(7)
    if wrench is None:
        wrench = np.array([1., -2., 3., -.4, .5, -.6])
    return Observation(q=q, tau_external=J.T @ wrench, jacobian=J, jacobian_q=q.copy(),
        joint_names=NAMES, jacobian_joint_names=NAMES, frame="world", tcp_point="left_fr3_side_suction_tcp",
        q_timestamp_s=1., torque_timestamp_s=1., jacobian_timestamp_s=1., evaluation_timestamp_s=1.01,
        torque_source="paired_static_load_difference", torque_provenance="synthetic pair 1",
        jacobian_provenance="synthetic analytical matrix")


def test_exact_full_rank_and_independent_lstsq():
    obs = sample()
    result = estimate(obs, CONTRACT)
    independent = lstsq(obs.jacobian.T, obs.tau_external)[0]
    assert result.status == "FULL_RANK" and result.rank == 6
    np.testing.assert_allclose(result.wrench_minimum_norm, independent, atol=2e-14)
    np.testing.assert_allclose(result.wrench_minimum_norm, [1, -2, 3, -.4, .5, -.6], atol=2e-14)
    assert result.reconstruction_residual_Nm < 1e-13


def test_nonzero_inconsistent_torque_is_not_silently_claimed_exact():
    obs = sample()
    # Orthogonal to column space of J.T: cannot be generated by any TCP wrench.
    u, _, _ = np.linalg.svd(obs.jacobian.T, full_matrices=True)
    obs = replace(obs, tau_external=obs.tau_external + .3 * u[:, -1])
    result = estimate(obs, CONTRACT)
    assert result.reconstruction_residual_Nm == pytest.approx(.3, abs=1e-13)


def test_rank_deficiency_reports_nonunique_observable_subspace():
    J = np.c_[np.diag([1., 1., 1., 1., 1., 0.]), np.zeros(6)]
    result = estimate(sample(J), CONTRACT)
    assert result.status == "RANK_DEFICIENT_NONUNIQUE" and result.rank == 5
    assert result.condition_number is None
    np.testing.assert_allclose(result.observable_projector, np.diag([1., 1., 1., 1., 1., 0.]))
    assert np.linalg.norm(J.T @ np.asarray(result.unobservable_basis).T) < 1e-14
    assert result.wrench_minimum_norm[5] == 0



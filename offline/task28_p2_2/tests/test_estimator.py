@pytest.mark.parametrize("delta", [np.zeros(7), np.array([.12, .1, -.14, .05, .12, -.08, .1])])
def test_frozen_fk_finite_difference_virtual_work_and_offset(delta):
    model = RobotModel()
    q = model.home + delta
    assert model.within_limits(q)
    J = model.jacobian("left", q)
    h = 1e-6
    columns = []
    for i in range(7):
        step = np.eye(7)[i] * h
        minus, plus = model.fk("left", q - step), model.fk("left", q + step)
        linear = (plus[:3, 3] - minus[:3, 3]) / (2 * h)
        angular = Rotation.from_matrix(plus[:3, :3] @ minus[:3, :3].T).as_rotvec() / (2 * h)
        columns.append(np.r_[linear, angular])
    independent_J = np.column_stack(columns)
    np.testing.assert_allclose(J, independent_J, atol=5e-9)
    # Force at p + r equals force and r x force moment at TCP p.
    force = np.array([2., -3., 5.])
    r = np.array([.04, -.03, .08])
    moment = np.cross(r, force)
    moment_J = np.vstack([independent_J[:3] - np.cross(r, independent_J[3:].T).T, independent_J[3:]])
    tau_from_offset = moment_J.T @ np.r_[force, np.zeros(3)]
    tau_at_tcp = J.T @ np.r_[force, moment]
    np.testing.assert_allclose(tau_from_offset, tau_at_tcp, atol=3e-8)
    obs = sample(J=J, q=q, wrench=np.r_[force, moment])
    result = estimate(obs, CONTRACT)
    assert result.rank == 6
    np.testing.assert_allclose(result.wrench_minimum_norm, np.r_[force, moment], atol=5e-12)



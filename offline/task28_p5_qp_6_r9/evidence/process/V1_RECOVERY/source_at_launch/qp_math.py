"""Centralized 14-DOF object-space kinematic QP.

The decision is arm velocity ``x in R^14``.  A six-dimensional null-space
constraint preserves the measured TCP pair's rigid relative twist; the common
virtual-object twist is a weighted soft task.  This is a kinematic QP only.
"""
from __future__ import annotations
import time
import numpy as np
from scipy.linalg import block_diag
from offline.task28_p5_qp_0.solver import solve_box_equality_qp
from offline.task28_g1_1.task28_validator.se3 import checked_transform
from .virtual_frames import VirtualCooperativeFrame


def skew(v):
    x, y, z = np.asarray(v, float)
    return np.array([[0., -z, y], [z, 0., -x], [-y, x, 0.]])


def object_to_tcp_map(T_WV, T_VT):
    """Map world object twist to world TCP twist for a fixed T_VT."""
    world = checked_transform(T_WV)
    T = checked_transform(T_VT)
    r = world[:3, :3] @ T[:3, 3]
    return np.block([[np.eye(3), -skew(r)], [np.zeros((3, 3)), np.eye(3)]])


def stack_jacobians(model, q14):
    q = np.asarray(q14, float)
    if q.shape != (14,) or not np.isfinite(q).all():
        raise ValueError("INVALID_Q14")
    return np.block([[model.jacobian("left", q[:7]), np.zeros((6, 7))],
                     [np.zeros((6, 7)), model.jacobian("right", q[7:])]])


def virtual_twist(t_s, duration_s, amplitude_m, axis="x"):
    """C2 zero-end-velocity world translation for the virtual object."""
    if duration_s <= 0 or amplitude_m <= 0 or axis not in ("x", "z"):
        raise ValueError("INVALID_VIRTUAL_TRAJECTORY")
    u = min(max(float(t_s) / duration_s, 0.), 1.)
    s = u * u * (3. - 2. * u)
    ds = (6. * u * (1. - u)) / duration_s if 0. < u < 1. else 0.
    twist = np.zeros(6); twist[0 if axis == "x" else 2] = amplitude_m * ds
    return twist, s


def virtual_pose(frame: VirtualCooperativeFrame, t_s, duration_s, amplitude_m, axis="x"):
    _, s = virtual_twist(t_s, duration_s, amplitude_m, axis)
    T = frame.T_WV.copy()
    T[0 if axis == "x" else 2, 3] += amplitude_m * s
    return T


def _relative_projector(frame: VirtualCooperativeFrame):
    H = np.vstack([object_to_tcp_map(frame.T_WV, frame.T_VL),
                   object_to_tcp_map(frame.T_WV, frame.T_VR)])
    # H has rank six for every valid rigid pair.  This is the orthogonal
    # complement of TCP twists that cannot be generated by one common object.
    P = np.eye(12) - H @ np.linalg.pinv(H, rcond=1e-12)
    return H, P


def solve_cooperative_qp(model, q14, frame, t_s, duration_s=1.5,
                         amplitude_m=0.001, axis="x", previous=None,
                         dt=1/60, qdot_limit=0.12):
    started = time.perf_counter()
    q = np.asarray(q14, float)
    if q.shape != (14,) or not np.isfinite(q).all() or previous is not None and (np.asarray(previous).shape != (14,)):
        raise ValueError("INVALID_QP_STATE")
    previous = np.zeros(14) if previous is None else np.asarray(previous, float)
    J = stack_jacobians(model, q)
    Hobj, P = _relative_projector(frame)
    desired_twist, _ = virtual_twist(t_s, duration_s, amplitude_m, axis)
    target = Hobj @ desired_twist
    # Hard relative-pair compatibility; soft common motion and joint smoothness.
    C = P @ J
    Wt = np.diag(np.r_[np.ones(6), np.ones(6)]) * 50.
    Ws = np.eye(14) * 0.25
    H = J.T @ Wt.T @ Wt @ J + Ws.T @ Ws + np.eye(14) * 1e-8
    f = -J.T @ Wt.T @ Wt @ target - Ws.T @ Ws @ previous
    lower = np.full(14, -float(qdot_limit)); upper = np.full(14, float(qdot_limit))
    result = solve_box_equality_qp(H, f, C, lower, upper, primal_tolerance=2e-8, kkt_tolerance=2e-7)
    if result.x is None:
        return None, {"status": result.status, "diagnostics": result.diagnostics,
                      "calculation_time_s": time.perf_counter() - started,
                      "hard_constraint_rows": int(C.shape[0]), "execution_authorized": False}
    x = np.asarray(result.x)
    achieved = J @ x
    rel_res = C @ x
    task_res = achieved - target
    diag = dict(result.diagnostics)
    diag.update({"status": "QP_OPTIMAL", "dimension": 14, "hard_constraint_rows": int(C.shape[0]),
                 "hard_relative_residual_inf": float(np.max(np.abs(rel_res), initial=0.)),
                 "common_task_residual_inf": float(np.max(np.abs(task_res), initial=0.)),
                 "qdot_inf": float(np.max(np.abs(x), initial=0.)),
                 "qdot_limit": float(qdot_limit), "target_twist": target.tolist(),
                 "achieved_tcp_twist": achieved.tolist(), "calculation_time_s": time.perf_counter() - started,
                 "hard_constraints": ["finite_source", "14D_joint_velocity_box", "virtual_TCP_relative_twist"],
                 "soft_objective": ["common_virtual_object_twist", "joint_smoothness"],
                 # The solver result is a mathematical candidate.  The runtime
                 # must still perform source, geometry, effort and latch gates.
                 "execution_authorized": False, "inverse_dynamics_claim": False})
    return x, diag


def finite_difference_jacobian(model, side, q, eps=1e-7):
    q = np.asarray(q, float); analytic = model.jacobian(side, q)
    numeric = np.zeros_like(analytic)
    for j in range(7):
        plus, minus = q.copy(), q.copy(); plus[j] += eps; minus[j] -= eps
        dp = (model.fk(side, plus)[:3, 3] - model.fk(side, minus)[:3, 3]) / (2*eps)
        # Rotation columns are compared against the analytic world angular axes.
        R0 = model.fk(side, q)[:3, :3]
        Rp, Rm = model.fk(side, plus)[:3, :3], model.fk(side, minus)[:3, :3]
        dR = (Rp - Rm) / (2*eps) @ R0.T
        numeric[:, j] = np.r_[dp, [dR[2, 1], dR[0, 2], dR[1, 0]]]
    return analytic, numeric
